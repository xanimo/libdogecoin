/* BIP152 short-id known answers.
 *
 * BIP152 publishes no test vectors -- bip-0152 in the bitcoin/bips repository
 * contains a diagram and nothing else -- so unlike BIP158 there is nothing
 * official to pin against. These were computed by an independent
 * implementation of the BIP152 derivation:
 *
 *     k0 || k1 = SHA256(block_header || nonce_le)   (single SHA256, LE u64s)
 *     short_id = low 6 bytes of SipHash-2-4(k0, k1, txid)
 *
 * That reference implementation was itself checked against the eight published
 * SipHash-2-4 reference vectors from Aumasson & Bernstein before being used to
 * produce anything here, so this is a known-answer test rather than two
 * implementations agreeing by luck.
 *
 * The header is 0x00..0x4f and the nonce is fixed, chosen only to be
 * reproducible: any deriving implementation must produce these bytes.
 */

